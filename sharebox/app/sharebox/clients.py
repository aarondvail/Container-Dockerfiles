"""Thin clients for the Torrust Tracker management API and the qBittorrent Web API."""
import logging

import httpx

from . import config

log = logging.getLogger("sharebox")


class TrackerAPI:
    """Torrust Tracker REST API v1 (private_listed mode)."""

    def __init__(self):
        self.c = httpx.Client(base_url=f"{config.TRACKER_API_URL}/api/v1",
                              params={"token": config.TRACKER_API_TOKEN}, timeout=20)

    def whitelist_add(self, infohash):
        self.c.post(f"/whitelist/{infohash}").raise_for_status()

    def whitelist_remove(self, infohash):
        r = self.c.delete(f"/whitelist/{infohash}")
        if r.status_code not in (200, 404, 500):  # 500 = wasn't listed
            r.raise_for_status()

    def key_create(self):
        """Permanent key (seconds_valid = null), generated by the tracker."""
        r = self.c.post("/keys", json={"key": None, "seconds_valid": None})
        r.raise_for_status()
        return r.json()["key"]

    def key_delete(self, key):
        r = self.c.delete(f"/key/{key}")
        if r.status_code not in (200, 404, 500):
            r.raise_for_status()


class QBit:
    """qBittorrent Web API v2. Auth is normally bypassed by subnet whitelist
    (QBIT_AUTH_BYPASS); QBIT_USER/QBIT_PASS are used if set."""

    def __init__(self):
        self.c = httpx.Client(base_url=config.QBIT_URL, timeout=60)
        self._logged_in = False

    def _login(self):
        if not config.QBIT_USER:
            return
        r = self.c.post("/api/v2/auth/login",
                        data={"username": config.QBIT_USER, "password": config.QBIT_PASS})
        if r.text.strip() != "Ok.":
            raise RuntimeError(f"qBittorrent login failed: {r.status_code} {r.text[:80]}")
        self._logged_in = True

    def _req(self, method, path, **kw):
        if config.QBIT_USER and not self._logged_in:
            self._login()
        r = self.c.request(method, path, **kw)
        if r.status_code == 403 and config.QBIT_USER:
            self._login()
            r = self.c.request(method, path, **kw)
        r.raise_for_status()
        return r

    def ensure_category(self):
        try:
            self._req("POST", "/api/v2/torrents/createCategory",
                      data={"category": config.QBIT_CATEGORY, "savePath": ""})
        except httpx.HTTPStatusError as e:
            if e.response.status_code != 409:  # 409 = already exists
                raise

    def hashes(self):
        r = self._req("GET", "/api/v2/torrents/info", params={"category": config.QBIT_CATEGORY})
        return {t["hash"].lower() for t in r.json()}

    def add(self, blob, savepath, name):
        r = self._req("POST", "/api/v2/torrents/add",
                      files={"torrents": (f"{name}.torrent", blob, "application/x-bittorrent")},
                      data={"savepath": savepath, "category": config.QBIT_CATEGORY,
                            "skip_checking": "true", "paused": "false", "stopped": "false",
                            "autoTMM": "false", "contentLayout": "Original"})
        if r.text.strip() not in ("Ok.", ""):
            raise RuntimeError(f"qBittorrent refused torrent: {r.text[:120]}")

    def delete(self, infohash):
        self._req("POST", "/api/v2/torrents/delete",
                  data={"hashes": infohash, "deleteFiles": "false"})
